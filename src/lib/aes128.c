/* Round constants */
static const uint8_t rcon[10] = { 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36 };

/* GF(2^8) multiply by 2 */
static inline uint8_t xtime(uint8_t x) { return (uint8_t)((x << 1) ^ (((x >> 7) & 1) * 0x1B)); }

static void key_expansion(const uint8_t key[16], uint8_t rk[AES128_ROUND_KEYS])
{
    memcpy(rk, key, 16);
    for(int i = 4; i < 44; i++)
    {
        uint8_t t[4];
        memcpy(t, &rk[(i - 1) * 4], 4);
        if(i % 4 == 0)
        {
            uint8_t tmp = t[0];
            t[0]        = sbox[t[1]] ^ rcon[i / 4 - 1];
            t[1]        = sbox[t[2]];
            t[2]        = sbox[t[3]];
            t[3]        = sbox[tmp];
        }
        for(int j = 0; j < 4; j++) rk[i * 4 + j] = rk[(i - 4) * 4 + j] ^ t[j];
    }
}

static void add_round_key(uint8_t state[16], const uint8_t *rk) {
    for(int i = 0; i < 16; i++) state[i] ^= rk[i];
}

static void sub_bytes(uint8_t state[16]) {
    for(int i = 0; i < 16; i++) state[i] = sbox[state[i]];
}

static void inv_sub_bytes(uint8_t state[16]) {
    for(int i = 0; i < 16; i++) state[i] = inv_sbox[state[i]];
}

static void shift_rows(uint8_t s[16])
{
    uint8_t t;
    /* Row 1: shift left 1 */
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    /* Row 2: shift left 2 */
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    /* Row 3: shift left 3 */
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

static void inv_shift_rows(uint8_t s[16])
{
    uint8_t t;
    /* Row 1: shift right 1 */
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    /* Row 2: shift right 2 */
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    /* Row 3: shift right 3 */
    t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}

static void mix_columns(uint8_t s[16])
{
    for(int i = 0; i < 4; i++)
    {
        int     c = i * 4;
        uint8_t a = s[c], b = s[c + 1], d = s[c + 2], e = s[c + 3];
        uint8_t x = a ^ b ^ d ^ e;
        s[c]     ^= x ^ xtime(a ^ b);
        s[c + 1] ^= x ^ xtime(b ^ d);
        s[c + 2] ^= x ^ xtime(d ^ e);
        s[c + 3] ^= x ^ xtime(e ^ a);
    }
}

static void inv_mix_columns(uint8_t s[16])
{
    for(int i = 0; i < 4; i++)
    {
        int     c = i * 4;
        uint8_t a = s[c], b = s[c + 1], d = s[c + 2], e = s[c + 3];
        uint8_t u = xtime(xtime(a ^ d));
        uint8_t v = xtime(xtime(b ^ e));
        s[c] ^= u; s[c + 1] ^= v; s[c + 2] ^= u; s[c + 3] ^= v;
    }
    mix_columns(s);
}

static void aes128_encrypt_block(const uint8_t rk[AES128_ROUND_KEYS], const uint8_t in[16], uint8_t out[16])
{
    uint8_t state[16];
    memcpy(state, in, 16);
    add_round_key(state, rk);
    for(int r = 1; r < 10; r++)
    {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, rk + r * 16);
    }
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, rk + 160);
    memcpy(out, state, 16);
}

static void aes128_decrypt_block(const uint8_t rk[AES128_ROUND_KEYS], const uint8_t in[16], uint8_t out[16])
{
    uint8_t state[16];
    memcpy(state, in, 16);
    add_round_key(state, rk + 160);
    for(int r = 9; r >= 1; r--)
    {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, rk + r * 16);
        inv_mix_columns(state);
    }
    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, rk);
    memcpy(out, state, 16);
}

void aes128_init(struct aes128_ctx *ctx, const uint8_t key[AES128_KEY_SIZE])
{
    key_expansion(key, ctx->round_keys);
    /* Pre-compute decryption round keys (same expansion, decrypt uses reverse order internally) */
    memcpy(ctx->dec_round_keys, ctx->round_keys, AES128_ROUND_KEYS);
}

void aes128_cbc_decrypt(const struct aes128_ctx *ctx, const uint8_t iv[AES128_BLOCK_SIZE], const uint8_t *in,
                        uint8_t *out, size_t len)
{
    uint8_t prev[16];
    memcpy(prev, iv, 16);
    for(size_t i = 0; i < len; i += 16)
    {
        uint8_t tmp[16];
        aes128_decrypt_block(ctx->round_keys, in + i, tmp);
        for(int j = 0; j < 16; j++) out[i + j] = tmp[j] ^ prev[j];
        memcpy(prev, in + i, 16);
    }
}

void aes128_cbc_encrypt(const struct aes128_ctx *ctx, const uint8_t iv[AES128_BLOCK_SIZE], const uint8_t *in,
                        uint8_t *out, size_t len)
{
    uint8_t chain[16];
    memcpy(chain, iv, 16);
    for(size_t i = 0; i < len; i += 16)
    {
        uint8_t tmp[16];
        for(int j = 0; j < 16; j++) tmp[j] = in[i + j] ^ chain[j];
        aes128_encrypt_block(ctx->round_keys, tmp, out + i);
        memcpy(chain, out + i, 16);
    }
}
